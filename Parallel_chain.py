
# from detailed report -> we extract notes and quiz -> user

"""from report 1 -> model 1 -> Notes
from model 2 -> Quiz 
Notes and Quiz -> model 3
merge the output and send to user

we use parallei chains here to generate notes and quiz in parallel from the report generated by model 1. The output of both chains is then merged and sent to the user. This allows for efficient processing and generation of multiple outputs simultaneously, improving the overall user experience.
 """



from langchain_openai import ChatOpenAI
from langchain_anthropic import ChatAnthropic
from dotenv import load_dotenv
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_core.runnables import RunnableParallel



load_dotenv()

model1 = ChatOpenAI()

model2 = ChatAnthropic(model_name = 'Claude-3')

prompt1 = PromptTemplate(
    templates = 'Generate short and simple notes from the following text \n {text}',
    input_variables = ['text']
)

prompt2 = PromptTemplate(
    templates = 'Generate 5 short questions answers from the following text \n {text}',     
    input_variables = ['text']
)


prompt3 = PromptTemplate(
    template = 'Merge the  provided notes and quiz into a single document \n Notes: {notes} \n Quiz: {quiz}',
    input_variables = ['notes', 'quiz']     
)

parser = StrOutputParser()

parallel_chain = RunnableParallel(
    {
        'notes': prompt1 | model1 | parser,
        'quiz': prompt2 | model2 | parser
    }
)

merge_chain = prompt3 | model1 | parser


chain = parallel_chain | merge_chain

result = chain.invoke({'text': 'Space exploration is the ongoing discovery and exploration of celestial structures in outer space by means of continuously evolving and growing space technology. It involves the use of astronomy and space technologies to explore outer space. While the study of space is carried out mainly by astronomers with telescopes, its physical exploration though is conducted both by unmanned robotic space probes and human spaceflight. Space exploration has often been used as a proxy competition for geopolitical rivalries such as the Cold War. The early era of space exploration was driven by a "Space Race" between the Soviet Union and the United States. With the launch of Sputnik 1 in 1957, the Soviet Union became the first nation to put a satellite into orbit. In response, the United States established NASA in 1958, which led to a series of manned spaceflights and eventually to the Apollo program that landed humans on the Moon in 1969. Since then, space exploration has expanded to include many countries and private companies, leading to advancements in satellite technology, international cooperation on projects like the International Space Station (ISS), and plans for future missions to Mars and beyond.'})

print(result)

chain.get_graph().print_ascii() # to check our chain structure














































